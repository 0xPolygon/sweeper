#!/usr/bin/env bash
# Usage: script/hevm.sh <recovery-address>
# Builds the runtime code for <recovery-address> and proves each property in hevm/ with hevm.
# Env: SOLVER (z3), SMT_TIMEOUT seconds per query (300), SMT_MEMORY MB per solver (3000), MAX_ITER (1000).
set -uo pipefail
RECOVERY="${1:?usage: $0 <recovery-address>}"
SOLVER="${SOLVER:-z3}"
SMT_TIMEOUT="${SMT_TIMEOUT:-300}"
SMT_MEMORY="${SMT_MEMORY:-3000}"
cd "$(dirname "$0")/.."

OUT="$(script/runtime-code.sh "$RECOVERY")" || exit 1
RUNTIME="$(awk '/^runtime:/ {print $2}' <<<"$OUT")"
HASH="$(awk '/^keccak:/ {print $2}' <<<"$OUT")"
ADDR="$(awk '/^recovery:/ {print $2}' <<<"$OUT")"
cat > hevm/SweeperRuntime.sol <<SOL
// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

// Generated by script/hevm.sh.
library SweeperRuntime {
    address internal constant RECOVERY = $ADDR;
    bytes32 internal constant CODEHASH = $HASH;
    bytes internal constant CODE = hex"${RUNTIME#0x}";
}
SOL
echo "recovery: $ADDR"
echo "keccak:   $HASH"

FOUNDRY_PROFILE=hevm forge clean && FOUNDRY_PROFILE=hevm forge build --ast --quiet || exit 1

PROPS=(codeIsRuntime opcodeScan valueReverts unknownSelectorReverts getterMovesNothing sweepPaysRecovery
  failedTransferReverts reentrancyBounded)
FAILED=0
for p in "${PROPS[@]}"; do
  LOG="$(mktemp)"
  START=$(date +%s)
  FOUNDRY_PROFILE=hevm /usr/bin/time -f '%M' -o "$LOG.mem" hevm test --root . --match "^prove_${p}\$" \
    --solver "$SOLVER" --num-solvers 1 --smt-timeout "$SMT_TIMEOUT" --smt-memory "$SMT_MEMORY" --max-iterations "${MAX_ITER:-1000}" >"$LOG.raw" 2>&1
  CODE=$?
  sed 's/\x1b\[[0-9;]*m//g' "$LOG.raw" >"$LOG"
  SECS=$(( $(date +%s) - START ))
  MEM="$(( $(tail -1 "$LOG.mem" 2>/dev/null || echo 0) / 1024 ))MB"
  if grep -qE "\[PASS\] prove_${p}\b" "$LOG" && [ $CODE -eq 0 ] && ! grep -qE 'WARNING|CAVEAT|partially|[Tt]ime ?out' "$LOG"; then
    STATUS=PASS
  elif grep -qE "\[FAIL\] prove_${p}\b" "$LOG" && grep -qE 'Counterexample' "$LOG"; then
    STATUS=FAIL; FAILED=1
  else
    STATUS=UNDECIDED; FAILED=1
  fi
  printf '%-24s %-9s %4ss  %s\n' "$p" "$STATUS" "$SECS" "$MEM"
  [ "$STATUS" = PASS ] || sed 's/^/    /' "$LOG" | tail -40
  rm -f "$LOG" "$LOG.raw" "$LOG.mem"
done
exit $FAILED
